"""Write src/content/voiceSamples.ts from WORK/selection.json and WORK/calls.json.
No engine names reach the site: a voice is its name, gender and languages."""
import json
from pathlib import Path

from render_gallery import OUT as VOICES_DIR, slug
from screen import WORK
from texts import CALL_USE_CASES, CALLS, GALLERY, USE_CASES

ROOT = Path(__file__).resolve().parents[2]
BLURBS = {
    "lead-qualification": "Qualify a fresh enquiry and book the next step.",
    "appointment-booking": "Turn an enquiry into a confirmed visit with a time.",
    "payment-reminders": "Remind, agree a date and send a payment link.",
    "feedback-surveys": "Collect a rating and the reason behind it.",
}


def main():
    picks = json.loads((WORK / "selection.json").read_text())
    calls = json.loads((WORK / "calls.json").read_text())
    library = []
    for c in sorted(picks, key=lambda c: c["name"]):
        langs = [l for l in ("en", "hi", "bn") if l in c["ids"]
                 and all((VOICES_DIR / slug(c) / f"{l}-{uc}.mp3").exists() for uc in USE_CASES)]
        if langs:
            library.append({"id": slug(c), "name": c["name"], "gender": c["gender"], "langs": langs})
    scripts = {uc: {"label": label, "text": {l: GALLERY[l][uc].replace("{rahi}", "रही/रहा")
                                             for l in GALLERY}}
               for uc, label in USE_CASES.items()}
    use_cases = [{"slug": s, "title": t, "blurb": BLURBS[s], "context": CALLS[s]["context"]}
                 for s, t in CALL_USE_CASES.items()]
    out_calls = [{"useCase": c["useCase"], "lang": c["lang"],
                  "src": f"/samples/calls/{c['useCase']}-{c['lang']}.mp3", "secs": c["secs"],
                  "agent": c["agent"], "agentGender": c["agentGender"], "turns": c["turns"]}
                 for c in calls]
    j = lambda v: json.dumps(v, ensure_ascii=False, indent=2)
    ts = f"""// Generated by scripts/samples/manifest.py — edit the scripts, not this file.
export type SampleLang = "en" | "hi" | "bn";
export type VoiceScript = "sales" | "reminder" | "feedback";
export type LibraryVoice = {{ id: string; name: string; gender: "female" | "male"; langs: SampleLang[] }};
export type CallTurn = {{ who: "agent" | "caller"; text: string; t: number }};
export type SampleCall = {{
  useCase: string; lang: SampleLang; src: string; secs: number;
  agent: string; agentGender: "female" | "male"; turns: CallTurn[];
}};

export const SAMPLE_LANGS: Record<SampleLang, {{ label: string; short: string }}> = {{
  en: {{ label: "English", short: "EN" }},
  hi: {{ label: "Hinglish", short: "HI" }},
  bn: {{ label: "Bengali", short: "BN" }},
}};

export const VOICE_SCRIPTS: Record<VoiceScript, {{ label: string; text: Record<SampleLang, string> }}> = {j(scripts)};

export const LIBRARY: LibraryVoice[] = {j(library)};

export const CALL_USE_CASES: {{ slug: string; title: string; blurb: string; context: string }}[] = {j(use_cases)};

export const CALLS: SampleCall[] = {j(out_calls)};

export const voiceClip = (id: string, lang: SampleLang, script: VoiceScript) =>
  `/samples/voices/${{id}}/${{lang}}-${{script}}.mp3`;
"""
    (ROOT / "src" / "content" / "voiceSamples.ts").write_text(ts)
    print(f"{len(library)} voices, {len(out_calls)} calls")


if __name__ == "__main__":
    main()
